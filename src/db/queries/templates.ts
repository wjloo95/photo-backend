/**
 * src/db/queries/templates.ts
 *
 * Query functions for form_templates + form_questions.
 *
 * form_questions has no query functions of its own on purpose: a template and
 * its questions are written as one whole set (ASSIGNMENTS.md 8.1), so every
 * function here that touches form_questions owns the entire set and runs
 * inside a transaction. There is deliberately no insertQuestion /
 * updateQuestion / deleteQuestion — "order" is the index of the submitted
 * array, and nothing is allowed to move a single question out from under it.
 *
 * Row types and mappers follow the same shape as queries/conversations.ts:
 * one interface mirroring the table's snake_case columns, one toX function
 * converting it to the camelCase entity in types/index.ts.
 */
import { PoolClient } from 'pg';
import { pool } from '../../config/database';
import { AnswerType, FormQuestion, FormTemplate } from '../../types';
import { AppError } from '../../types/AppError';

export interface FormTemplateRow {
  id: string;
  photographer_id: string; // FK → Photographer.userId
  name: string;
  created_at: Date;
}

export function toFormTemplate(row: FormTemplateRow): FormTemplate {
  return {
    id: row.id,
    photographerId: row.photographer_id,
    name: row.name,
    createdAt: row.created_at,
  };
}

export interface FormQuestionRow {
  id: string;
  template_id: string; // FK → FormTemplate.id
  content: string;
  answer_type: AnswerType;
  order: number; // 0-based index of the submitted array (migration 018)
}

export function toFormQuestion(row: FormQuestionRow): FormQuestion {
  return {
    id: row.id,
    templateId: row.template_id,
    content: row.content,
    answerType: row.answer_type,
    order: row.order,
  };
}

/**
 * A template with its questions embedded, in "order" sequence — the shape
 * GET /templates/:id returns, and the shape POST/PUT return after writing.
 *
 * Not a raw table mirror (it spans two tables), so like ClientWithUser in
 * queries/clients.ts this type lives here rather than in types/index.ts.
 */
export interface TemplateWithQuestions extends FormTemplate {
  questions: FormQuestion[];
}

/**
 * One question as it arrives in a request body. No id and no order: ids are
 * generated by the DB, and order is the index this entry sat at in the
 * submitted array — the caller never sends either.
 */
export interface QuestionInput {
  content: string;
  answerType: AnswerType;
}

export interface TemplateFields {
  name: string;
  questions: QuestionInput[];
}

/**
 * Inserts a template's whole question set and returns the created rows.
 *
 * Takes an already checked-out client rather than the pool, so it composes
 * inside either caller's transaction — POST creates the set, PUT replaces it,
 * and both need the identical insert. One copy is what keeps the
 * "order = array index" convention from drifting between the two.
 *
 * On the loop: this is N round trips, one per question — a deliberate choice,
 * resting on two facts. The set is bounded at MAX_QUESTIONS (25, rejected in
 * the route before any transaction opens), and both callers are cold write
 * paths a photographer hits while building a form, not the read paths this
 * app is sized for. What it costs is connection-hold time (the pool is
 * max: 10), which at this arrival rate is not the scarce resource. What it
 * buys: a failing question is identifiable by index, there is no
 * `($1,$2,$3,$4),($5,...)` placeholder arithmetic to get wrong when a column
 * is added, and each returned row maps back to a known position rather than
 * relying on RETURNING order, which the standard does not guarantee.
 *
 * Note what does NOT speed this up: wrapping the inserts in Promise.all.
 * node-postgres queues queries per client and dispatches the next only when
 * the previous completes, so that is the same N sequential round trips minus
 * the error attribution. Spreading them across pooled clients would put them
 * in different transactions and lose the atomicity this exists for. Inside
 * one transaction the only way to cut round trips is to send fewer statements.
 *
 * Revisit if the 25 cap rises to thousands, a bulk-import path reuses this,
 * or it lands somewhere hot. The replacement is a single multi-row
 * INSERT ... RETURNING *, which would also need an explicit empty-array guard
 * (an empty VALUES list is a syntax error). This version accepts an empty
 * array silently and inserts nothing — the 1-question minimum is the route's
 * job, validated at the edge.
 */
async function insertQuestions(
  client: PoolClient,
  templateId: string,
  questions: QuestionInput[],
): Promise<FormQuestion[]> {
  const created: FormQuestion[] = [];

  // entries() carries the index for "order" without a hand-rolled counter.
  for (const [i, q] of questions.entries()) {
    const result = await client.query<FormQuestionRow>(
      `INSERT INTO form_questions (template_id, content, answer_type, "order")
       VALUES ($1, $2, $3, $4)
       RETURNING *`,
      [templateId, q.content, q.answerType, i],
    );

    created.push(toFormQuestion(result.rows[0]));
  }

  return created;
}

/**
 * POST /templates — the template row and all of its question rows, atomically.
 *
 * Same pool.connect() transaction shape as insertClientFromInvite in
 * queries/users.ts: BEGIN, insert the parent, insert the children, COMMIT —
 * ROLLBACK and rethrow on any error, release in a finally. created_at is left
 * to its column DEFAULT NOW() (migration 009).
 *
 * "order" comes from the array index, never from the body and never from
 * MAX("order") + 1 — see insertQuestions above.
 */
export async function insertTemplateWithQuestions(
  photographerId: string,
  fields: TemplateFields,
): Promise<TemplateWithQuestions> {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');

    const templateResult = await client.query<FormTemplateRow>(
      `INSERT INTO form_templates (photographer_id, name)
         VALUES ($1, $2)
         RETURNING *`,
      [photographerId, fields.name],
    );

    const templateRow = templateResult.rows[0];
    const template = toFormTemplate(templateRow);

    const resultQuestions = await insertQuestions(client, template.id, fields.questions);

    await client.query('COMMIT');

    return { ...template, questions: resultQuestions };
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  } finally {
    client.release();
  }
}

/**
 * The template row alone, no questions.
 *
 * The ownership-check load that PUT and DELETE run before they mutate: they
 * need photographer_id and nothing else, so they don't pay for the questions
 * join. Guards on rows[0] before mapping — pg types rows[0] as present even
 * when the result is empty, so `toFormTemplate(rows[0]) ?? null` would throw
 * on a miss instead of returning null (the ?? applies to the call's result,
 * not its argument).
 */
export async function getTemplateById(id: string): Promise<FormTemplate | null> {
  const templateResult = await pool.query<FormTemplateRow>(
    `SELECT * FROM form_templates WHERE id = $1`,
    [id],
  );
  return templateResult.rows[0] ? toFormTemplate(templateResult.rows[0]) : null;
}

/**
 * One row of the template + questions join.
 *
 * A LEFT JOIN either matched a question or it didn't, and when it didn't every
 * q.* column in the row is NULL together — so this is a union of those two
 * states rather than four independently-nullable columns. That makes
 * `question_id === null` a discriminant: one check narrows all four question
 * fields at once, and the mapping below needs no non-null assertions.
 *
 * The template columns keep their FormTemplateRow names so toFormTemplate can
 * map a row directly. The question columns are aliased because `id` and
 * `content` collide with the template's own — worth naming, because with
 * `SELECT t.*, q.*` node-postgres keeps only the last `id` in the row object,
 * and the template's id silently becomes the question's.
 */
type TemplateQuestionJoinRow = FormTemplateRow &
  (
    | { question_id: string; question_content: string; answer_type: AnswerType; order: number }
    | { question_id: null; question_content: null; answer_type: null; order: null }
  );

/**
 * GET /templates/:id — the template with its questions in "order" sequence.
 *
 * One round trip via a LEFT JOIN, regrouped here. The join repeats the
 * template's columns on every question row (at most 25, so the duplication is
 * cheap) and returns a single all-NULL-question row for a template that has
 * none — which is why the join is LEFT, and why the WHERE clause filters on
 * `t.id` alone. Any condition on `q.*` in WHERE would drop that row and
 * quietly turn this into an inner join, 404ing a template that exists; a
 * filter on questions belongs in the ON clause instead.
 *
 * Returns null only when the template itself doesn't exist. A template with
 * zero questions still returns, with `questions: []` — unreachable through
 * these functions (the route requires at least one), but a read path
 * shouldn't 404 on data it can plainly see.
 */
export async function getTemplateWithQuestionsById(
  id: string,
): Promise<TemplateWithQuestions | null> {
  const result = await pool.query<TemplateQuestionJoinRow>(
    `SELECT t.id,
            t.photographer_id,
            t.name,
            t.created_at,
            q.id      AS question_id,
            q.content AS question_content,
            q.answer_type,
            q."order"
     FROM form_templates t
     LEFT JOIN form_questions q ON q.template_id = t.id
     WHERE t.id = $1
     ORDER BY q."order" ASC`,
    [id],
  );

  const [first] = result.rows;

  if (!first) {
    return null;
  }

  // flatMap over the union: the no-questions row contributes [] rather than a
  // null-filled FormQuestion. template_id comes from t.id — the join defines
  // it as the same value q.template_id holds, so it needn't be selected twice.
  const questions = result.rows.flatMap((row) =>
    row.question_id === null
      ? []
      : [
          toFormQuestion({
            id: row.question_id,
            template_id: row.id,
            content: row.question_content,
            answer_type: row.answer_type,
            order: row.order,
          }),
        ],
  );

  return { ...toFormTemplate(first), questions };
}

/**
 * GET /photographers/:id/templates — a photographer's own templates.
 *
 * Same shape as getPendingInvitesByPhotographerId in queries/invites.ts.
 * List view only — no questions embedded. The caller picks one and calls
 * GET /templates/:id for the full form.
 */
export async function getTemplatesByPhotographerId(
  photographerId: string,
): Promise<FormTemplate[]> {
  const resultTemplates = await pool.query<FormTemplateRow>(
    `SELECT * FROM form_templates WHERE photographer_id = $1 ORDER BY created_at DESC`,
    [photographerId],
  );

  return resultTemplates.rows.map(toFormTemplate);
}

/**
 * Has this template ever been assigned to a client?
 *
 * SELECT 1 rather than COUNT(*) or SELECT *: the question is existence, and
 * LIMIT 1 lets Postgres stop at the first hit instead of scanning every
 * response attached to the template.
 *
 * DELETE only, since migration 019. This used to guard PUT as well — a replace
 * recreates question rows with new ids, which would have orphaned
 * form_answers.question_id, so an assigned template was frozen outright and
 * edited by duplication. Responses now snapshot their questions and reference
 * no question rows at all, so editing is always safe and PUT needs no check.
 *
 * Deleting is still blocked: a response is a standalone record of what a
 * client was asked and answered, and form_responses.template_id is
 * ON DELETE RESTRICT (migration 019), so the database refuses regardless. This
 * check exists to turn that into a 409 with an explanation instead of a
 * foreign-key violation surfacing as a 500.
 */
export async function templateHasResponses(id: string): Promise<boolean> {
  const templateResult = await pool.query(
    `SELECT 1
     FROM form_responses
     WHERE template_id = $1
     LIMIT 1`,
    [id],
  );

  return templateResult.rows.length > 0;
}

/**
 * PUT /templates/:id — replace the name and the entire question set.
 *
 * One transaction: UPDATE the name, DELETE every question, insert the new set
 * via the same insertQuestions helper POST uses, COMMIT. Delete-then-insert
 * inside one transaction is why the UNIQUE (template_id, "order") constraint
 * from migration 018 doesn't fight this — the old rows are gone before the new
 * ones land, and no other writer can interleave.
 *
 * A missing template throws AppError 404 rather than returning null, so the
 * exit routes through the catch below and the transaction is rolled back
 * before the client goes back to the pool. A plain `return` from inside the
 * try would release a client with BEGIN still open, and the next borrower
 * would inherit that open transaction — releasing does not roll back.
 *
 * This used to run behind a lock check in the route, with a check-then-write
 * race between the two. Migration 019 removed the reason for the lock rather
 * than tightening it: responses snapshot their questions, so recreating
 * question rows here cannot orphan anything, and there is no longer a state in
 * which a template may not be edited.
 */
export async function replaceTemplateQuestions(
  id: string,
  fields: TemplateFields,
): Promise<TemplateWithQuestions> {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');

    const templateResult = await client.query<FormTemplateRow>(
      `UPDATE form_templates
       SET name = $2
        WHERE id = $1
         RETURNING *`,
      [id, fields.name],
    );

    const templateRow = templateResult.rows[0];

    if (!templateRow) {
      throw new AppError('Template not found', 404);
    }
    const template = toFormTemplate(templateRow);

    await client.query(`DELETE FROM form_questions WHERE template_id = $1`, [id]);

    const resultQuestions = await insertQuestions(client, template.id, fields.questions);

    await client.query('COMMIT');

    return { ...template, questions: resultQuestions };
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  } finally {
    client.release();
  }
}

/**
 * DELETE /templates/:id.
 *
 * No transaction and no question cleanup — ON DELETE CASCADE on
 * form_questions.template_id (migration 010) removes them. Same void-return
 * convention as deleteInviteById; the route has already loaded the row to
 * authorise, so there's nothing left to return.
 */
export async function deleteTemplateById(id: string): Promise<void> {
  await pool.query(`DELETE FROM form_templates WHERE id = $1`, [id]);
}
